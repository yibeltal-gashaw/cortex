import { ParsedConversationSession, TimelineStep, ToolCallItem } from './timelineParser.js';
import { maskAllCredentials } from './credentialScanner.js';

function escapeHtml(str: string): string {
  if (!str) return '';
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export function generateMarkdownRunbook(session: ParsedConversationSession): string {
  const parts: string[] = [];

  parts.push(`# Cortex Session Runbook: \`${session.id}\``);
  parts.push('');
  parts.push(`> **Generated by Cortex Session HUD** on ${new Date().toUTCString()}`);
  parts.push('');
  parts.push('### Session Intelligence & Telemetry');
  parts.push('| Metric | Value |');
  parts.push('| :--- | :--- |');
  parts.push(`| **Model** | \`${session.model || 'Unknown'}\` |`);
  parts.push(`| **Duration** | ${session.durationFormatted} (${session.durationMs}ms) |`);
  parts.push(`| **Total Steps** | ${session.totalSteps} |`);
  parts.push(`| **Prompt Tokens** | ${(session.tokenStats?.totalInputTokens || 0).toLocaleString()} fresh + ${(session.tokenStats?.totalCacheReadTokens || 0).toLocaleString()} cached |`);
  parts.push(`| **Output Tokens** | ${(session.tokenStats?.totalOutputTokens || 0).toLocaleString()} |`);
  parts.push(`| **Cache Hit Rate** | **${session.tokenStats?.cacheHitRatePercent || 0}%** |`);
  parts.push(`| **Estimated Cost** | **$${(session.tokenStats?.estimatedCostUsd || 0).toFixed(4)}** |`);
  if (session.subagents && session.subagents.length > 0) {
    parts.push(`| **Subagents Spawned** | ${session.subagents.length} child agent(s) |`);
  }
  parts.push('');
  parts.push('---');
  parts.push('## Execution Feed & Audit Trail');
  parts.push('');

  let turnIndex = 0;

  for (const step of session.steps) {
    if (step.type === 'USER_INPUT') {
      turnIndex++;
      parts.push(`### Turn ${turnIndex}: User Request`);
      const req = step.userPrompt?.requestText || step.userPrompt?.raw || 'User Prompt';
      parts.push('```markdown');
      parts.push(maskAllCredentials(req));
      parts.push('```');
      parts.push('');
    } else if (step.type === 'PLANNER_RESPONSE') {
      if (step.thinking) {
        parts.push('<details>');
        parts.push(`<summary><b>AI Reasoning & Planning (Step #${step.stepIndex})</b></summary>`);
        parts.push('');
        parts.push(maskAllCredentials(step.thinking));
        parts.push('');
        parts.push('</details>');
        parts.push('');
      }

      if (step.toolCalls && step.toolCalls.length > 0) {
        for (const tc of step.toolCalls) {
          const name = tc.name;
          const status = tc.result?.status || 'DONE';
          parts.push(`#### Tool: \`${name}\` [${status}]`);

          if (name === 'run_command' || name === 'run_terminal_cmd') {
            const cmd = tc.args.CommandLine || tc.args.command || '';
            const exitCode = tc.result?.exitCode ?? (status === 'ERROR' ? 1 : 0);
            parts.push(`**Command**: \`${maskAllCredentials(cmd)}\` *(Exit: ${exitCode})*`);
            if (tc.result?.content) {
              parts.push('```bash');
              parts.push(maskAllCredentials(tc.result.content));
              parts.push('```');
            }
          } else if (name === 'edit_file' || name === 'write_file' || name === 'replace_file_content' || name === 'write_to_file') {
            const targetFile = tc.result?.diff?.targetFile || tc.args.Path || tc.args.target_file || '';
            parts.push(`**Modified File**: \`${targetFile}\``);
            if (tc.result?.diff) {
              const { oldContent, newContent } = tc.result.diff;
              parts.push('```diff');
              if (oldContent) {
                parts.push(oldContent.split('\n').map(l => `- ${maskAllCredentials(l)}`).join('\n'));
              }
              if (newContent) {
                parts.push(newContent.split('\n').map(l => `+ ${maskAllCredentials(l)}`).join('\n'));
              }
              parts.push('```');
            }
          } else if (name === 'read_file' || name === 'view_file') {
            const p = tc.args.Path || tc.args.path || '';
            parts.push(`**Inspected File**: \`${p}\``);
          } else if (name === 'invoke_subagent') {
            const role = tc.args.Role || tc.args.role || 'Subagent';
            const prompt = tc.args.Prompt || tc.args.prompt || '';
            parts.push(`**Spawned Subagent**: \`${role}\``);
            parts.push(`> ${maskAllCredentials(prompt)}`);
          } else {
            parts.push('```json');
            parts.push(maskAllCredentials(JSON.stringify(tc.args, null, 2)));
            parts.push('```');
            if (tc.result?.content) {
              parts.push('**Result**:');
              parts.push('```text');
              parts.push(maskAllCredentials(tc.result.content.slice(0, 1000)));
              parts.push('```');
            }
          }
          parts.push('');
        }
      }

      if (step.assistantResponse) {
        parts.push('#### Assistant Response:');
        parts.push(maskAllCredentials(step.assistantResponse));
        parts.push('');
      }
    }
  }

  return parts.join('\n');
}

